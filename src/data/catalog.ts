export type PaperSummary = {
  title: string;
  sessions: number;
  years: string;
};

/** Paper titles and session counts for every subject, generated by tools/topical/catalog.mjs. */
export const PAPER_INDEX = index as Record<string, Record<string, PaperSummary>>;

export function getSubject(key: string | null | undefined): Subject | undefined {
  return SUBJECTS.find((s) => s.key === key);
}

export function paperSummary(subject: string, paper: string): PaperSummary | undefined {
  return PAPER_INDEX[subject]?.[paper];
}

export function subjectPaperCount(key: string): number {
  return Object.values(PAPER_INDEX[key] ?? {}).reduce((n, p) => n + p.sessions, 0);
}

// Each subject's links are their own chunk, loaded when one of its papers opens.
const PAPERS = import.meta.glob<SubjectPapers>(["./papers/*.json", "!./papers/index.json"], { import: "default" });

export function loadPapers(subject: string): Promise<SubjectPapers> {
  const load = PAPERS[`./papers/${subject}.json`];
  if (!load) return Promise.reject(new Error(`No papers for ${subject}`));
  return load();
}
